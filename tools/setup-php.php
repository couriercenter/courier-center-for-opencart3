<?php
/**
 * Downloads the portable PHP builds (Windows x64) used by lint, tests and the
 * local test shops, and writes tools/config.php.
 * Usage (Git Bash): /c/xampp/php/php.exe tools/setup-php.php
 */
require __DIR__ . '/lib/common.php';

$base   = 'C:/Users/python/php-versions';
$cainfo = 'C:/xampp/apache/bin/curl-ca-bundle.crt';
$builds = array(
    '7.0' => 'php-7.0.33-Win32-VC14-x64.zip',
    '7.2' => 'php-7.2.34-Win32-VC15-x64.zip',
    '7.4' => 'php-7.4.33-Win32-vc15-x64.zip',
    '8.1' => 'php-8.1.34-Win32-vs16-x64.zip',
    '8.5' => 'php-8.5.11-Win32-vs17-x64.zip',
);
$mirrors = array('https://windows.php.net/downloads/releases/archives/', 'https://windows.php.net/downloads/releases/');

function cc_download_file($url, $dest) {
    $fp = fopen($dest, 'wb');
    $ch = curl_init($url);
    curl_setopt_array($ch, array(
        CURLOPT_FILE => $fp, CURLOPT_FOLLOWLOCATION => true, CURLOPT_FAILONERROR => true,
        CURLOPT_USERAGENT => 'Mozilla/5.0 (cc-setup)', CURLOPT_TIMEOUT => 900,
    ));
    $ok = curl_exec($ch);
    fclose($fp);
    if (!$ok || filesize($dest) < 1000000) {
        @unlink($dest);
        return false;
    }
    return true;
}

$paths = array('8.2' => 'C:/xampp/php/php.exe');
foreach ($builds as $ver => $zip) {
    $dir = $base . '/php' . str_replace('.', '', $ver);
    if (!is_file($dir . '/php.exe')) {
        @mkdir($dir, 0777, true);
        $tmp = $base . '/' . $zip;
        $got = false;
        foreach ($mirrors as $m) {
            if (cc_download_file($m . $zip, $tmp)) {
                $got = true;
                break;
            }
        }
        if (!$got) {
            fwrite(STDERR, "Download failed: $zip (check https://windows.php.net/downloads/releases/ for the current $ver build and update \$builds)\n");
            exit(1);
        }
        $za = new ZipArchive();
        if ($za->open($tmp) !== true) {
            fwrite(STDERR, "Bad zip: $tmp\n");
            exit(1);
        }
        $za->extractTo($dir);
        $za->close();
        unlink($tmp);
    }
    $ini = file_get_contents($dir . '/php.ini-development');
    $ini .= "\n; ---- Courier Center test setup ----\nextension_dir = \"$dir/ext\"\n";
    foreach (array('php_curl.dll', 'php_mbstring.dll', 'php_mysqli.dll', 'php_openssl.dll', 'php_gd2.dll', 'php_gd.dll', 'php_zip.dll', 'php_fileinfo.dll') as $ext) {
        if (is_file("$dir/ext/$ext")) {
            $ini .= "extension=$ext\n";
        }
    }
    $ini .= "date.timezone = Europe/Athens\nmemory_limit = 512M\nupload_max_filesize = 2M\npost_max_size = 8M\nmax_execution_time = 300\n";
    $ini .= "curl.cainfo = \"$cainfo\"\nopenssl.cafile = \"$cainfo\"\n";
    file_put_contents($dir . '/php.ini', $ini);
    $paths[$ver] = $dir . '/php.exe';
    list(, $v) = cc_exec(array($dir . '/php.exe', '-r', 'echo PHP_VERSION;'));
    echo "PHP $ver -> $v\n";
}

$file = __DIR__ . '/config.php';
$cfg = is_file($file) ? require $file : require __DIR__ . '/config.example.php';
$cfg['php'] = $paths;
ksort($cfg['php']);
file_put_contents($file, "<?php\n// Generated by tools/setup-php.php (machine-specific, not committed).\nreturn " . var_export($cfg, true) . ";\n");
echo "Wrote tools/config.php\n";
